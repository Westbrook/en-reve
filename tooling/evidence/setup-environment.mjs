import { delimiter } from 'node:path';

// These variables are owned by the test harness, not by production generators.
// Remove them from the actual isolated producer environment as well as its key;
// merely deleting them from a cache key would permit unsound reuse.
export const testHarnessVariables=Object.freeze([
 'TEST_WORKER_INDEX','TEST_PARALLEL_INDEX',
 'EN_EXECUTION_OUTPUT','EN_TEST_PIPELINE_OUTPUT','EN_TEST_PIPELINE_CONFIG_OUTPUTS','EN_EXECUTION_OWN_SERVERS',
 'EN_THEME_TEST_OUTPUT_DIR','EN_RELEASE_TEST_OUTPUT_DIR','EN_READER_TEST_RECEIPT','EN_FRAMEWORK_INSTALL_RECEIPT',
 'EN_DOCS_ORIGIN','EN_WORKFLOW_BASE_URL','EN_REVE_PREVIEW_URL','EN_READER_ORIGIN','EN_PATTERN_GALLERY_URL','TOKEN_DOCS_URL',
 'EN_WORKFLOW_TEST_PORT','EN_WORKFLOW_TEST_OUTPUT_DIR','EN_THEME_REFRESH_OUTPUT_DIR','EN_THEME_CASCADE_OUTPUT_DIR',
 'EN_STATE_PAINT_OUTPUT_DIR','EN_COMPOSITION_OUTPUT_DIR','EN_API_CONTRACTS_TEST_OUTPUT_DIR',
 'EN_SIZE_TEST_PORT','EN_SIZE_TEST_OUTPUT','EN_COMMANDS_TEST_PORT','EN_COMMANDS_TEST_OUTPUT_DIR',
 'PROPERTY_TEST_OUTPUT_DIR','SCOPE_TEST_OUTPUT_DIR','EN_PAIR_EVIDENCE','EN_REVE_REGISTRATION_EVIDENCE_DIR',
 'EN_STICKER_TEST_OUTPUT_DIR','EVIDENCE_DIR','EN_AUTHORING_OUTPUT',
 'EN_SCOPED_REGISTRY_OUT','EN_LAZY_OUT','EN_ACTIVATION_OUT','EN_ACTIVATION_LIBRARY_OUT','EN_SCOPED_HYDRATION_OUT',
 'EN_PACKED_SETUP_RECEIPT','EN_API_SMOKE_OUTPUT_DIR','EN_API_SMOKE_BASE_URL','EN_CANDIDATES','EN_CANDIDATE_OUTPUT','EN_THEME_ASSETS_OUTPUT','EN_CANDIDATE_ORIGIN',
]);
export function setupEnvironment(environment=process.env,{production=true}={}) {
 const result={...environment};
 for(const key of testHarnessVariables)delete result[key];
 for(const key of ['PWD','OLDPWD','SHLVL','_','INIT_CWD','npm_lifecycle_event','npm_lifecycle_script'])delete result[key];
 // These isolated production generators never invoke npm; discard its caller
 // lifecycle/config context from the real environment as well as the identity.
 // Packing retains npm configuration and keys it separately.
 if(production)for(const key of Object.keys(result))if(key.startsWith('npm_'))delete result[key];
 if(production)result.NODE_ENV??='production';
 result.PATH=[...new Set((result.PATH??'').split(delimiter))].join(delimiter);
 return result;
}

// Ownership must reach nested commands, but it cannot change generated bytes.
// Keep this explicit exception separate from harness variables removed from
// the actual producer environment. Semantic options remain in every identity.
export const coordinationVariables=Object.freeze([
 'EN_TEST_EXECUTION_OWNER','EN_TEST_MACHINE_LOCK','EN_TEST_MACHINE_OWNER',
 'EN_GATE_MACHINE_LOCK','EN_GATE_MACHINE_OWNER','EN_GATE_BROWSER_LOCK','EN_GATE_BROWSER_OWNER',
]);
export function setupEnvironmentInputs(environment) {
 return Object.fromEntries(Object.entries(environment).filter(([key])=>!coordinationVariables.includes(key)));
}
